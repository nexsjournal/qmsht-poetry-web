/** 生成布帘文本：篇目 + 逐诗（题/作者 + 正文），全角空格分隔，竖排右起。 */
export function clothText(collectionId = "all") {
  const col = COLLECTIONS.find((c) => c.id === collectionId) || COLLECTIONS[0];
  const parts = ["清明诗选"];
  for (const p of POEMS) {
    if (!col.tiers.includes(p.tier)) continue;
    parts.push(`《${p.t}》${p.a}·${p.d}${p.text}`);
  }
  return parts.join("　");
}

export function clothCharCount(collectionId = "all") {
  return Array.from(clothText(collectionId)).length;
}
